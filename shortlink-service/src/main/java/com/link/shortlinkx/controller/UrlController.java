package com.link.shortlinkx.controller;

import com.link.shortlinkx.dto.CreateShortUrlRequest;
import com.link.shortlinkx.dto.ShortUrlResponse;
import com.link.shortlinkx.service.UrlService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.net.URI;
import java.util.List;

@RestController
@RequestMapping("/api/v1")
@RequiredArgsConstructor
@Tag(name = "URLs", description = "URL Shortener and redirection controller")
public class UrlController {

    private static final int MAX_IP_LENGTH = 45; // longest textual IPv6 address, matches analytics.ip_address

    private final UrlService urlService;

    @PostMapping("/shorten")
    @Operation(summary = "Shorten a URL", description = "Creates a random shortcode for the given original long URL and associates it with the authenticated user ID forwarded by the gateway.")
    public ResponseEntity<ShortUrlResponse> shorten(
            @RequestBody @Valid CreateShortUrlRequest request,
            @RequestHeader("X-User-Id") Long userId) {

        return ResponseEntity.ok(
                urlService.shortenUrl(request, userId)
        );
    }

    @GetMapping("/{shortCode:[a-zA-Z0-9]{1,10}}")
    @Operation(summary = "Redirect shortcode", description = "Resolves a shortcode into its original URL target and executes an HTTP 302 redirect.")
    public ResponseEntity<Void> redirect(
            @PathVariable String shortCode,
            @RequestHeader(value = "X-Forwarded-For", required = false) String xForwardedFor,
            @RequestHeader(value = "Referer", required = false) String referrer,
            @RequestHeader(value = "User-Agent", required = false) String userAgent,
            HttpServletRequest request) {

        String ipAddress = resolveClientIp(xForwardedFor, request);
        String originalUrl = urlService.getOriginalUrlAndRecordClick(shortCode, ipAddress, referrer, userAgent);

        HttpHeaders headers = new HttpHeaders();
        headers.setLocation(URI.create(originalUrl));

        return new ResponseEntity<>(
                headers,
                HttpStatus.FOUND
        );
    }

    @GetMapping("/urls")
    @Operation(summary = "Get user link history", description = "Fetches the shortened URLs generated by the authenticated user, newest first, one page at a time (size is capped at 100).")
    public ResponseEntity<List<ShortUrlResponse>> getUrlHistory(
            @RequestHeader("X-User-Id") Long userId,
            @RequestParam(defaultValue = "0") int page,
            @RequestParam(defaultValue = "50") int size) {

        return ResponseEntity.ok(
                urlService.getUrlsByUserId(userId, page, size)
        );
    }

    /**
     * The gateway discards any client-supplied X-Forwarded-For and sets its own, so the first entry is the
     * client address. The value is still validated because this service must never fail on odd input.
     */
    private String resolveClientIp(String xForwardedFor, HttpServletRequest request) {
        if (xForwardedFor != null && !xForwardedFor.isBlank()) {
            String first = xForwardedFor.split(",", 2)[0].trim();
            if (first.length() <= MAX_IP_LENGTH && first.matches("[0-9a-fA-F:.]+")) {
                return first;
            }
        }
        return request.getRemoteAddr();
    }
}
